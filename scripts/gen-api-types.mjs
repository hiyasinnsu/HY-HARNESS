// Generates `packages/hy-cli/web/src/api.gen.ts` from the API contract.
//
// The client imports this file instead of hard-coding route data, and
// `pnpm check:api` fails when the checked-in copy drifts from the contract
// (`api-contract.ts`).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const contractPath = path.join(repo, 'packages', 'hy-cli', 'dist', 'api-contract.js')
const outPath = path.join(repo, 'packages', 'hy-cli', 'web', 'src', 'api.gen.ts')

const { API_ROUTES } = await import(pathToFileURL(contractPath).href)

const quote = (value) => JSON.stringify(value)

const fields = (request) =>
  Object.entries(request ?? {})
    .map(([name, spec]) => `    ${name}: { type: ${quote(spec.type)}${spec.required ? ', required: true' : ''} },`)
    .join('\n')

const routes = API_ROUTES.map((route) => {
  const lines = [
    '  {',
    `    method: ${quote(route.method)},`,
    `    path: ${quote(route.path)},`,
    `    summary: ${quote(route.summary)},`,
  ]
  if (route.response) lines.push(`    response: ${quote(route.response)},`)
  if (route.errors?.length) lines.push(`    errors: [${route.errors.join(', ')}],`)
  if (route.request) lines.push(`    request: {\n${fields(route.request)}\n    },`)
  lines.push('  },')
  return lines.join('\n')
})

const generated = `// GENERATED by scripts/gen-api-types.mjs from packages/hy-cli/src/api-contract.ts.
// Do not edit; run \`pnpm gen:api\` (or \`pnpm check:api\` in CI).
/* eslint-disable */

export type FieldType = 'string' | 'number' | 'boolean' | 'object' | 'array' | 'images'

export interface ApiRouteField {
  type: FieldType
  required?: true
}

export interface ApiRouteInfo {
  method: 'GET' | 'POST' | 'PUT' | 'DELETE'
  path: string
  summary: string
  response?: string
  errors?: number[]
  request?: Record<string, ApiRouteField>
}

export const API_ROUTES: readonly ApiRouteInfo[] = [
${routes.join('\n')}
]

/** Fills a contract path's \`:params\` from an object. */
export function apiPath(pattern: string, params: Record<string, string | number> = {}): string {
  return pattern.replace(/:([A-Za-z0-9_]+)/g, (_match, name: string) => {
    const value = params[name]
    if (value === undefined) throw new Error(\`apiPath: missing \${name} for \${pattern}\`)
    return encodeURIComponent(String(value))
  })
}

/** The declared route for a method + concrete path, if any. */
export function findApiRoute(method: string, pathname: string): ApiRouteInfo | undefined {
  const target = pathname.split('?')[0] ?? pathname
  const parts = target.split('/').filter(Boolean)
  return API_ROUTES.find((route) => {
    if (route.method !== method.toUpperCase()) return false
    const pattern = route.path.split('/').filter(Boolean)
    if (pattern.length !== parts.length) return false
    return pattern.every((part, index) => part.startsWith(':') || part === parts[index])
  })
}
`

fs.mkdirSync(path.dirname(outPath), { recursive: true })
const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : ''
if (process.argv.includes('--check')) {
  if (current !== generated) {
    console.error('api.gen.ts is out of date: run `pnpm gen:api`')
    process.exit(1)
  }
  console.log('web/src/api.gen.ts is up to date')
  process.exit(0)
}
fs.writeFileSync(outPath, generated, 'utf8')
console.log(`wrote ${path.relative(repo, outPath)} (${API_ROUTES.length} routes)`)
