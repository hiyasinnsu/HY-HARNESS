// Generates packages/core/src/protocol.gen.ts from the Rust protocol types.
// `--check` fails (exit 1) when the committed file differs from a fresh generation.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { compile } from 'json-schema-to-typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'packages', 'core', 'src', 'protocol.gen.ts')
const check = process.argv.includes('--check')
// `--schema <file>`: reuse a schema already produced by
// `cargo run -p hy-protocol --bin hy-protocol-schema`. Useful where spawning
// cargo from Node is not possible (a confined shell blocks piped children).
const schemaIndex = process.argv.indexOf('--schema')
const schemaText =
  schemaIndex >= 0
    ? readFileSync(process.argv[schemaIndex + 1], 'utf8')
    : execFileSync('cargo', ['run', '-q', '-p', 'hy-protocol', '--bin', 'hy-protocol-schema'], {
        cwd: root,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'inherit'],
      })
const schema = JSON.parse(schemaText)

const body = await compile(schema, 'HyProtocol', {
  bannerComment: '',
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
  format: true,
  style: { singleQuote: true, semi: false, printWidth: 120 },
})
// The root "HyProtocol" object type is only a container for definitions.
const cleaned = body.replace(/export interface HyProtocol \{[^}]*\}\n*/m, '')
const text =
  '// GENERATED by scripts/gen-protocol.mjs from crates/hy-protocol. Do not edit.\n' +
  '/* eslint-disable */\n\n' +
  cleaned.trimEnd() +
  '\n'

if (check) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current.replace(/\r\n/g, '\n') !== text) {
    process.stderr.write('protocol.gen.ts is out of date; run `pnpm gen:protocol`\n')
    process.exit(1)
  }
  process.stdout.write('protocol.gen.ts is up to date\n')
} else {
  writeFileSync(out, text)
  process.stdout.write(`wrote ${out}\n`)
}
