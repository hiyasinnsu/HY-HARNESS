const dictionaries: Record<Locale, Dict> = { en, ja, zh }

/**
 * WP-61 (U10): extra dictionaries can be merged at runtime, so adding a
 * language does not need a rebuild. An unknown locale falls back to English,
 * and an unknown key falls back to the key itself (visible, never blank).
 */
const extraDictionaries = new Map<string, Dict>()
const extraLabels = new Map<string, string>()

export function registerLocaleMessages(locale: string, messages: Dict, label?: string): void {
  if (!locale) throw new Error('locale must not be empty')
  const current = extraDictionaries.get(locale) ?? {}
  extraDictionaries.set(locale, { ...current, ...messages })
  if (label && !extraLabels.has(locale)) extraLabels.set(locale, label)
}

export function registeredLocales(): string[] {
  return [...extraDictionaries.keys()].sort()
}

/** The built-in locales plus any registered one (for the settings select). */
export function localeChoices(): Array<{ id: string; label: string }> {
  const choices = LOCALES.map((entry) => ({ id: entry.id as string, label: entry.label }))
  for (const [id, label] of extraLabels) {
    if (!choices.some((entry) => entry.id === id)) choices.push({ id, label })
  }
  return choices
}

export function detectLocale(): Locale {
  const saved = localStorage.getItem('hy-locale') as Locale | null
  if (saved && saved in dictionaries) return saved
  const language = navigator.language.toLowerCase()
  if (language.startsWith('ja')) return 'ja'
  if (language.startsWith('zh')) return 'zh'
  return 'en'
}

export function translate(locale: string, key: string, vars?: Record<string, string | number>): string {
  const dict = dictionaries[locale as Locale] ?? extraDictionaries.get(locale) ?? dictionaries.en
  let text = dict[key] ?? dictionaries.en[key] ?? key
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value))
  return text
}

/**
 * Whether `key` is declared in `locale` (or in English, the fallback). The
 * value itself cannot answer this: an English entry may equal its key
 * (`lines: 'lines'`).
 */
export function hasTranslation(locale: string, key: string): boolean {
  const dict = dictionaries[locale as Locale] ?? extraDictionaries.get(locale)
  if (dict && Object.prototype.hasOwnProperty.call(dict, key)) return true
  return Object.prototype.hasOwnProperty.call(dictionaries.en, key)
}
